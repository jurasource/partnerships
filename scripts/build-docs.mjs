#!/usr/bin/env node
/**
 * Build-time docs snapshot.
 *
 * Reads every Markdown file under `.planning/` and emits a statically-importable
 * TypeScript module (`src/lib/docs/docs.generated.ts`). Because the app imports
 * that module normally, the bundler includes it in the build output — so the
 * Documentation section works identically on Vercel, Railway, or locally,
 * without reading arbitrary repo files from disk at request time.
 *
 * Re-run automatically via the `predev` / `prebuild` npm scripts.
 */
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const DOCS_DIR = path.join(ROOT, ".planning");
const OUT_FILE = path.join(ROOT, "src", "lib", "docs", "docs.generated.ts");

/** Recursively collect absolute paths of every `*.md` file under `dir`. */
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(full)));
    } else if (entry.isFile() && entry.name.toLowerCase().endsWith(".md")) {
      files.push(full);
    }
  }
  return files;
}

/** First `# Heading`, else a humanized filename. */
function deriveTitle(content, relPath) {
  const match = content.match(/^#\s+(.+?)\s*$/m);
  if (match) return match[1].trim();
  const base = path.basename(relPath, ".md");
  return base.replace(/[-_]/g, " ").replace(/\s+/g, " ").trim();
}

async function main() {
  let absFiles = [];
  try {
    absFiles = await walk(DOCS_DIR);
  } catch {
    console.warn(`[build-docs] no .planning directory found at ${DOCS_DIR}; emitting empty docs.`);
  }

  const docs = [];
  for (const abs of absFiles) {
    const relPath = path.relative(DOCS_DIR, abs).split(path.sep).join("/");
    const content = await readFile(abs, "utf8");
    const slug = relPath.replace(/\.md$/i, "");
    docs.push({
      slug,
      relPath,
      segments: relPath.split("/"),
      title: deriveTitle(content, relPath),
      content,
    });
  }

  // Stable order: folders/files alphabetically by path.
  docs.sort((a, b) => a.relPath.localeCompare(b.relPath));

  const banner =
    "// AUTO-GENERATED by scripts/build-docs.mjs — DO NOT EDIT.\n" +
    "// Regenerate with `npm run docs:build` (also runs on predev/prebuild).\n" +
    "/* eslint-disable */\n";
  const body =
    'import type { GeneratedDoc } from "./types";\n\n' +
    `export const DOCS: GeneratedDoc[] = ${JSON.stringify(docs, null, 2)};\n`;

  await mkdir(path.dirname(OUT_FILE), { recursive: true });
  await writeFile(OUT_FILE, banner + body, "utf8");
  console.log(`[build-docs] wrote ${docs.length} docs to ${path.relative(ROOT, OUT_FILE)}`);
}

main().catch((err) => {
  console.error("[build-docs] failed:", err);
  process.exit(1);
});
